import { describe, expect, it } from 'vitest';
import { nativePaths, nativeSettings } from '../../src/runtime/native.ts';
import { giteaSettings, renderEnv, renderIni } from '../../src/runtime/settings.ts';

const secrets = { SECRET_KEY: 's', INTERNAL_TOKEN: 'i', JWT_SECRET: 'j', LFS_JWT_SECRET: 'l' };

describe('Gitea settings', () => {
  it('native: binds to 127.0.0.1 on the chosen port, with its own paths and secrets', () => {
    const p = nativePaths('/h');
    const s = nativeSettings(3514, p, secrets, 'kevin');
    expect(s.server).toMatchObject({ HTTP_ADDR: '127.0.0.1', HTTP_PORT: '3514', ROOT_URL: 'http://127.0.0.1:3514/', APP_DATA_PATH: '/h/gitea/data' });
    expect(s['']).toMatchObject({ APP_NAME: 'Slipway', RUN_USER: 'kevin', WORK_PATH: '/h/gitea' });
    expect(s.database).toEqual({ DB_TYPE: 'sqlite3', PATH: '/h/gitea/data/gitea.db' });
    expect(s.security).toMatchObject({ INSTALL_LOCK: 'true', SECRET_KEY: 's', INTERNAL_TOKEN: 'i' });
    expect(s.oauth2).toEqual({ JWT_SECRET: 'j' });
  });

  it('keeps the Slipway product rules in both runtimes: no sign-up, sign-in required, no merges-adjacent units', () => {
    const s = giteaSettings(3514);
    expect(s.service).toMatchObject({ DISABLE_REGISTRATION: 'true', REQUIRE_SIGNIN_VIEW: 'true' });
    expect(s.repository!.DEFAULT_REPO_UNITS).toBe('repo.code,repo.pulls');
    expect(s.security!.MIN_PASSWORD_LENGTH).toBe('6');
  });

  it('renders app.ini with the root section first', () => {
    const ini = renderIni({ '': { APP_NAME: 'Slipway' }, server: { HTTP_ADDR: '127.0.0.1' }, 'ui.meta': { AUTHOR: 'Slipway' } });
    expect(ini).toMatch(/^; Generated by Slipway.*\nAPP_NAME = Slipway\n\n\[server\]\nHTTP_ADDR = 127.0.0.1\n\n\[ui\.meta\]\nAUTHOR = Slipway\n$/s);
  });

  it('renders the Docker env file as GITEA__section__KEY', () => {
    const env = renderEnv(giteaSettings(3030));
    expect(env).toContain('GITEA____APP_NAME=Slipway\n');
    expect(env).toContain('GITEA__server__ROOT_URL=http://127.0.0.1:3030/\n');
    expect(env).toContain('GITEA__ui.meta__AUTHOR=Slipway\n');
    expect(env).not.toMatch(/HTTP_ADDR|APP_DATA_PATH/); // the container keeps its own listen address and paths
  });
});
