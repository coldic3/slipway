/** Deep merge: later sections/keys win. */
export function mergeSettings(...all: Sections[]): Sections {
  const out: Sections = {};
  for (const s of all) for (const [sec, kv] of Object.entries(s)) out[sec] = { ...out[sec], ...kv };
  return out;
}

export function renderIni(s: Sections): string {
  const lines: string[] = ['; Generated by Slipway on every `slipway up`. Do not edit: change src/runtime/settings.ts instead.'];
  const root = s[''] ?? {};
  for (const [k, v] of Object.entries(root)) lines.push(`${k} = ${v}`);
  for (const [sec, kv] of Object.entries(s)) {
    if (sec === '') continue;
    lines.push('', `[${sec}]`);
    for (const [k, v] of Object.entries(kv)) lines.push(`${k} = ${v}`);
  }
  return lines.join('\n') + '\n';
}

/** Docker env file: GITEA__section__KEY=value (root section: GITEA____KEY). */
export function renderEnv(s: Sections): string {
  const lines: string[] = [];
  for (const [sec, kv] of Object.entries(s)) for (const [k, v] of Object.entries(kv)) lines.push(`GITEA__${sec}__${k}=${v}`);
  return lines.join('\n') + '\n';
}
